// Compares the two collateral modes (upfront vs from the pot) with the parity-tested simulator and
// writes docs/MODE_COMPARISON.md.
//   Part 1: the lifecycle situations, side by side.
//   Part 2: EXHAUSTIVE for 3, 4 and 5 members: every member stops at any round or never; a member
//           who stops after their payout catches up never, in the next round, or in the cure
//           window; every cover level; fee 0 and 1%. Counts the scenarios where any member's
//           final result differs between modes, grouped by what happened, and the largest amount
//           a member who kept paying ends up worse off in from-pot mode.
//   node scripts/compare-modes.mjs        (about 30 seconds)
import { writeFileSync } from "node:fs";
import { simulate } from "../app/src/sim.js";
import { lifecycle } from "./lifecycle-scenarios.mjs";

const C = 100_000_000n; // 100 tokens; results are shown in contributions (c)
const inC = (v) => {
  const t = (Number(v) / Number(C)).toFixed(2).replace(/\.00$/, "");
  return t === "-0" ? "0" : t;
};
const COVERS = [0, 2000, 3000, 4000, 5000, 10000];



let out = `# Collateral modes compared: upfront vs from the pot

Generated by \`node scripts/compare-modes.mjs\` from the simulator, which matches the contract's full state after every step (\`test/Sim.parity.test.js\`). The lifecycle rows are also run on the contract itself, in both modes, by \`test/ModeLifecycle.test.js\`. Amounts are in contributions (c). "Net" is what each member ends with, minus what they put in.

**From the pot** (v9.2.1): a member locks the smaller of its seat's collateral and one contribution to join. At its payout, the rest of its seat's collateral is held back from the pot. Pot money that reaches it later (repayments of a short payout) tops the collateral up to the same seat amount.

## Lifecycle situations

| Situation | Cover | Nets, upfront | Nets, from the pot | Same? |
| --- | --- | --- | --- | --- |
`;
for (const [name, sc] of lifecycle) {
  const p = { c: C, feeBps: 0, stopAt: [], catchUpAt: [], ...sc };
  const a = simulate({ ...p, fromPayout: false });
  const b = simulate({ ...p, fromPayout: true });
  if (!a.conserved || !b.conserved) throw new Error(`not conserved: ${name}`);
  const same = a.members.every((m, i) => m.net === b.members[i].net);
  out += `| ${name} | ${p.k / 100}% | ${a.members.map((m) => inC(m.net)).join(", ")} | ${b.members.map((m) => inC(m.net)).join(", ")} | ${same ? "yes" : "**no**"} |\n`;
}

// Part 2: exhaustive small circles
const groups = new Map();
let tested = 0;
for (const n of [3, 4, 5]) {
  const opts = n + 1;
  for (let code = 0; code < opts ** n; code++) {
    const stopAt = [];
    let x = code;
    for (let i = 0; i < n; i++) {
      stopAt.push(x % opts);
      x = Math.floor(x / opts);
    }
    const cuChoices = stopAt.map((s, i) => (s > i + 1 ? [0, Math.min(s + 1, n), n + 1] : [0]));
    const combos = cuChoices.reduce((acc, ch) => acc.flatMap((a) => ch.map((c) => [...a, c])), [[]]);
    for (const catchUpAt of combos) {
      for (const k of COVERS) {
        for (const feeBps of [0, 100]) {
          const p = { n, c: C, k, feeBps, stopAt, catchUpAt };
          const a = simulate({ ...p, fromPayout: false });
          const b = simulate({ ...p, fromPayout: true });
          tested++;
          const leftEarly = stopAt.some((s, i) => s > 0 && s <= i + 1);
          const walked = stopAt.some((s, i) => s > i + 1 && !catchUpAt[i]);
          const key = `${k}|${leftEarly}|${walked}`;
          const g = groups.get(key) || { k, leftEarly, walked, tested: 0, differ: 0, worstForPayer: 0n };
          g.tested++;
          let differ = false;
          a.members.forEach((m, i) => {
            const d = b.members[i].net - m.net;
            if (d !== 0n) differ = true;
            if (!stopAt[i] && -d > g.worstForPayer) g.worstForPayer = -d;
          });
          if (differ) g.differ++;
          groups.set(key, g);
        }
      }
    }
  }
}

out += `
## Exhaustive comparison, 3 to 5 members

${tested.toLocaleString("en-US")} scenarios. Every member stops at any round or never; a member who stops after its payout catches up never, in the next round or in the cure window. Every cover level, fee 0 and 1%.

| Cover | Someone stopped before its own payout | Someone stopped after its payout, never caught up | Scenarios | Any result differs | Most a member who kept paying is worse off in from-pot mode |
| --- | --- | --- | --- | --- | --- |
`;
let anyOther = false;
for (const g of [...groups.values()].sort((x, y) => x.k - y.k || Number(x.leftEarly) - Number(y.leftEarly) || Number(x.walked) - Number(y.walked))) {
  if (g.differ && !(g.leftEarly && g.walked)) anyOther = true;
  out += `| ${g.k / 100}% | ${g.leftEarly ? "yes" : "no"} | ${g.walked ? "yes" : "no"} | ${g.tested.toLocaleString("en-US")} | ${g.differ.toLocaleString("en-US")} | ${inC(g.worstForPayer)} |\n`;
}
out += `
## What this shows

- **Results are identical** in every scenario except one combination: a member stops before its own payout **and** another member stops after its payout and never catches up.${anyOther ? " (Not true for this run: see the rows above.)" : ""}
- **Why that combination differs:** a member who stops before its payout is refunded what it paid and its collateral at the end, after members who are owed money. In upfront mode an early seat's leftover collateral is large and helps repay them; in from-pot mode it only ever locked up to one share, so there is less to recover from.
- **At 100% cover nobody who keeps paying is ever worse off** in from-pot mode; the differences are between members who stopped.
- **After a short payout**, a member's collateral is below its seat's amount until the shortfall is repaid. That is real, and visible on its seat card, but it changed no final result in these scenarios.
- **Leaving in round 1** costs the same in both modes, because the join amount is a full share (capped at the seat's collateral), not share × cover.

Not covered here: circles larger than 5 members (the random parity tests cover up to 12), and partial repayment orders the simulator does not model (it mirrors the contract's oldest-first rule exactly).
`;
writeFileSync(new URL("../docs/MODE_COMPARISON.md", import.meta.url), out);
console.log(`docs/MODE_COMPARISON.md written: ${tested} exhaustive scenarios`);
