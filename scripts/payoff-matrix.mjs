// Seat-by-seat payoff analysis, computed with the contract-verified simulator (app/src/sim.js).
// Writes docs/PAYOFF_MATRIX.md.   Run: node scripts/payoff-matrix.mjs
import { writeFileSync } from "node:fs";
import { simulate, honest } from "../app/src/sim.js";

const C = 1_000_000n; // 1 token with 6 decimals; results are per 1 unit of contribution
const COVERS = [0, 2000, 3000, 4000, 5000, 10000];
const SIZES = [2, 3, 6, 12];
const FEE = 50;
const fmt = (v) => {
  const neg = v < 0n;
  const a = neg ? -v : v;
  const s = `${a / C}.${String(a % C).padStart(6, "0")}`.replace(/\.?0+$/, "");
  return (neg ? "-" : v > 0n ? "+" : "") + (s === "" ? "0" : s);
};
const sum = (xs) => xs.reduce((a, b) => a + b, 0n);

let out = `# PotLoop payoff matrix

Generated by \`node scripts/payoff-matrix.mjs\` with the settlement simulator in \`app/src/sim.js\`,
which \`test/Sim.parity.test.js\` checks against the deployed contract logic base unit for base unit.

Amounts are in units of one contribution (c = 1), fee ${FEE / 100}%. "Net" is everything a member
gets back minus everything they sent in (collateral, payments, catch-ups). Every scenario conserves
money: the sum of all nets plus the treasury fee is exactly zero.

Strategies, for the member in the seat shown:
- **Honest**: pays every round.
- **Walk away**: takes the pot, then never pays again (no catch-up).
- **Gain**: walk-away net minus honest net. Positive = defaulting pays.
- **Others lose**: how much worse off all other members are together, compared with everyone honest.
- **Catch up at end**: walks away after the pot, then catches up in the cure window. Cost vs honest.
- **Leave at start**: stops in round 1, before their turn (seat 1 can't: round 1 is its turn).

Two collateral modes (v9.2), both shown:
- **Upfront**: a seat locks all of its collateral to join.
- **From pot**: every seat locks the smaller of its collateral and one share to join; the rest is held
  back from its own pot at its turn and returned at the end. "In hand" is what the seat can withdraw at its turn (pot after fee,
  minus what is held). Walk-away, catch-up and leave-at-start results are identical in both modes
  (checked below for every row). See docs/MODE_COMPARISON.md for the one combination where they differ.

`;

const summary = [];
for (const n of SIZES) {
  for (const k of COVERS) {
    const base = honest({ n, c: C, k, feeBps: FEE });
    out += `\n## ${n} members, ${k / 100}% cover\n\n| Seat | Collateral (full) | To join: upfront / from pot | In hand at turn (from pot) | Honest net | Walk-away gain | Others lose | Catch up at end (cost) | Leave at start: upfront / from pot |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n`;
    const potBase = honest({ n, c: C, k, feeBps: FEE, fromPayout: true });
    let maxGain = 0n;
    for (let s = 0; s < n; s++) {
      const stopAt = Array(n).fill(0);
      stopAt[s] = s + 2 <= n ? s + 2 : 0;
      const walk = simulate({ n, c: C, k, feeBps: FEE, stopAt });
      const cu = Array(n).fill(0);
      cu[s] = stopAt[s] ? n + 1 : 0;
      const caught = simulate({ n, c: C, k, feeBps: FEE, stopAt, catchUpAt: cu });
      const leaveAt = Array(n).fill(0);
      leaveAt[s] = s === 0 ? 0 : 1;
      const leave = simulate({ n, c: C, k, feeBps: FEE, stopAt: leaveAt });
      const walkP = simulate({ n, c: C, k, feeBps: FEE, stopAt, fromPayout: true });
      const caughtP = simulate({ n, c: C, k, feeBps: FEE, stopAt, catchUpAt: cu, fromPayout: true });
      const leaveP = simulate({ n, c: C, k, feeBps: FEE, stopAt: leaveAt, fromPayout: true });
      for (const r of [walk, caught, leave, walkP, caughtP, leaveP]) if (!r.conserved) throw new Error("not conserved");
      if (walkP.members[s].net - potBase.members[s].net !== walk.members[s].net - base.members[s].net) throw new Error(`walk-away differs by mode: n=${n} k=${k} seat ${s + 1}`);
      if (caughtP.members[s].net !== caught.members[s].net) throw new Error(`catch-up differs by mode: n=${n} k=${k} seat ${s + 1}`);
      if (s > 0 && leaveP.members[s].net !== leave.members[s].net) throw new Error(`leave-at-start differs by mode: n=${n} k=${k} seat ${s + 1}`);
      const pm = potBase.members[s];
      const inHand = pm.potAtTurn - (pm.potAtTurn * BigInt(FEE)) / 10000n - pm.heldFromPot;
      const gain = walk.members[s].net - base.members[s].net;
      const othersLose = sum(base.members.filter((_, j) => j !== s).map((x) => x.net)) - sum(walk.members.filter((_, j) => j !== s).map((x) => x.net));
      const cuCost = base.members[s].net - caught.members[s].net;
      if (gain > maxGain) maxGain = gain;
      const plain = (v) => fmt(v).replace("+", "");
      out += `| ${s + 1} | ${plain(walk.members[s].collateralLocked)} | ${plain(walk.members[s].collateralLocked)} / ${plain(pm.collateralLocked)} | ${plain(inHand)} | ${fmt(base.members[s].net)} | ${stopAt[s] ? fmt(gain) : "n/a (last seat)"} | ${stopAt[s] ? plain(othersLose) : "n/a"} | ${stopAt[s] ? fmt(cuCost) : "n/a"} | ${s === 0 ? "n/a" : `${fmt(leave.members[s].net)} / ${fmt(leaveP.members[s].net)}`} |\n`;
    }
    // coordinated: the first half of the seats all walk away after their payouts
    const m = Math.max(1, Math.floor(n / 2));
    const co = Array(n).fill(0);
    for (let s = 0; s < m; s++) co[s] = s + 2 <= n ? s + 2 : 0;
    const coord = simulate({ n, c: C, k, feeBps: FEE, stopAt: co });
    const coGain = sum(coord.members.slice(0, m).map((x) => x.net)) - sum(base.members.slice(0, m).map((x) => x.net));
    const honestLoss = sum(base.members.slice(m).map((x) => x.net)) - sum(coord.members.slice(m).map((x) => x.net));
    out += `\nCoordinated: seats 1–${m} (one person with ${m} wallets) all walk away after their pots: they gain ${fmt(coGain)} together; seats ${m + 1}–${n} lose ${fmt(honestLoss).replace("+", "")} together.\n`;
    summary.push({ n, k, maxGain, coGain });
  }
}

out += `\n## Summary: most a single member gains by walking away\n\n| Members | ${COVERS.map((k) => `${k / 100}%`).join(" | ")} |\n| --- | ${COVERS.map(() => "---").join(" | ")} |\n`;
for (const n of SIZES) {
  out += `| ${n} | ${COVERS.map((k) => fmt(summary.find((x) => x.n === n && x.k === k).maxGain)).join(" | ")} |\n`;
}
out += `
## What this shows

- At **100% cover**, walking away after your turn gains nothing: your collateral pays every round you
  still owe, and nobody else loses anything. Defaulting is neutral for you and harmless for the group.
- Below 100%, the walk-away gain for seat s is about (N − 1 − s) × c × (1 − cover): the part of what
  you still owe that your collateral doesn't cover. It is largest for seat 1 in big circles. The same
  amount is lost by the members paid after you. No penalty that only uses money already in the
  contract can remove this without asking for more collateral, so the honest answer is: **below 100%
  cover, the circle runs partly on trust**, and the app shows each seat's exact walk-away gain before
  anyone joins.
- Catching up costs the 2% late fee on the arrears compared with paying on time, minus your own share
  of that fee when it is shared out at the end; members who were paid short are repaid.
- Leaving before your turn costs up to one contribution (taken from what you paid in plus your
  collateral); the members who stay share it.
- **From-pot collateral** cuts the money needed to join to at most one share for every seat (12 members
  at 100%: seat 1 needs 1 instead of 11) with the same walk-away, catch-up and leave-early results. The
  cost: at 100% cover seat 1 has only about 2 of its 12-share pot in hand at its turn (the rest backs
  what it still owes).
`;
writeFileSync(new URL("../docs/PAYOFF_MATRIX.md", import.meta.url), out);
console.log(out.split("## Summary")[1]);
