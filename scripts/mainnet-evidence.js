// Builds MAINNET_TRANSACTION_EVIDENCE.md from the reports in mainnet-runs/.
//   node scripts/mainnet-evidence.js
// Only MODE=live reports (chain 1990) are listed as mainnet evidence, with explorer links.
// Fork rehearsals are summarised separately and clearly marked: their hashes exist only on a
// local copy and cannot be looked up on the explorer.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const dir = path.join(ROOT, "mainnet-runs");
const EXPLORER = "https://mainnet.qie.digital";
const runs = fs.existsSync(dir)
  ? fs
      .readdirSync(dir)
      .filter((f) => /^(live|fork)-S\d-.*\.json$/.test(f))
      .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")))
      .sort((a, b) => a.at.localeCompare(b.at))
  : [];
const live = runs.filter((r) => r.mode === "live" && r.chainId === "1990");
const fork = runs.filter((r) => r.mode === "fork");
const fmtQie = (wei) => (Number(BigInt(wei)) / 1e18).toFixed(6);

let md = `# PotLoop mainnet transaction evidence

Generated by \`node scripts/mainnet-evidence.js\` from \`mainnet-runs/\`. Every hash below links to the QIE mainnet explorer.

**How to read this file.** It is organised per scenario report, as the runner wrote them. Scenario 6 continues the circle of scenario 5, so its table repeats scenario 5's first 37 transactions (marked *(S5)*), and its gas and fee lines include them: do not add the sections together. The authoritative one-row-per-transaction list, with receipt status, sender, destination and fee re-read from the chain, is \`MAINNET_TRANSACTIONS.csv\`; attempts are in \`MAINNET_RUN_ATTEMPTS.csv\`, circles in \`MAINNET_CIRCLES.csv\`, and the totals in \`MAINNET_FINANCIAL_RECONCILIATION.md\`.

`;
if (!live.length) {
  md += `**No mainnet runs yet.** Nothing has been sent to QIE mainnet. This file fills in automatically after each approved live scenario.\n\n`;
} else {
  for (const r of live) {
    md += `## Scenario ${r.scenario}: ${r.title}\n\n`;
    if (r.adoptedFrom) md += `- The first ${r.transactions.filter((t) => t.adopted).length} transactions were sent by the first runner (log \`${r.adoptedFrom}\`), which stopped when its command time ran out; the resumable runner re-read each of them from its receipt and continued from the next step.\n`;
    if (r.continuedFrom) md += `- Finishes the circle of ${r.continuedFrom}. The first ${r.carriedOver} transactions (marked S5) are S5's and are included in this run's gas and fee totals; the simulator expectation covers the whole circle.\n`;
    md += `- Outcome: **${r.outcome}** (${r.passed} checks passed, ${r.failed} failed)${r.error ? `; stopped: ${r.error}` : ""}\n`;
    md += `- Approval code: \`${r.approval}\`; run at ${r.at}\n`;
    md += `- Factory [${r.factory}](${EXPLORER}/address/${r.factory}), deployer [${r.deployer}](${EXPLORER}/address/${r.deployer})\n`;
    md += `- Gas ${r.gasUsed}, fees ${fmtQie(r.feesWei)} QIE; your wallet ${fmtQie(r.funder_qie_before)} → ${fmtQie(r.funder_qie_after)} QIE, ${Number(r.funder_qusdc_before) / 1e6} → ${Number(r.funder_qusdc_after) / 1e6} QUSDC\n`;
    for (const c of r.circles) {
      md += `\n### ${c.label}: circle [${c.circle}](${EXPLORER}/address/${c.circle})\n\n`;
      md += `${c.config.n} members, ${Number(c.config.contribution) / 1e6} QUSDC per round, ${c.config.coverBps / 100}% cover, collateral ${c.config.fromPayout ? "from the pot" : "up front"}.\n\n`;
      md += c.checks.map((k) => `- ${k.ok ? "PASS" : "FAIL"} ${k.name}${k.detail ? ` (${k.detail})` : ""}`).join("\n") + "\n";
    }
    md += `\n| # | Step | Transaction | Gas used (estimate) | Fee (QIE) | Events |\n| --- | --- | --- | --- | --- | --- |\n`;
    r.transactions.forEach((t, i) => {
      md += `| ${i + 1} | ${t.label}${t.status === "reverted" ? " **(refused by the contract)**" : ""}${r.carriedOver && i < r.carriedOver ? " (S5)" : ""} | [${t.hash.slice(0, 10)}…](${EXPLORER}/tx/${t.hash}) | ${t.gasUsed} (${t.gasEstimate ?? "—"}) | ${fmtQie(t.feeWei)} | ${t.events.join("; ").slice(0, 160)} |\n`;
    });
    md += "\n";
  }
}
if (fork.length) {
  md += `## Rehearsals on a local copy of QIE mainnet (not mainnet evidence)\n\nRun with \`MODE=fork\`: the real QUSDC contract and real chain state, but every transaction stays on the local copy.\n\n| Run at | Scenario | Outcome | Checks passed / failed | Transactions | Gas |\n| --- | --- | --- | --- | --- | --- |\n`;
  for (const r of fork) md += `| ${r.at} | ${r.scenario} | ${r.outcome} | ${r.passed} / ${r.failed} | ${r.transactions.length} | ${r.gasUsed} |\n`;
}
fs.writeFileSync(path.join(ROOT, "MAINNET_TRANSACTION_EVIDENCE.md"), md);
console.log(`MAINNET_TRANSACTION_EVIDENCE.md: ${live.length} mainnet runs, ${fork.length} rehearsals`);
